CREATE TABLE customer
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    customer_name VARCHAR(255),
    email         VARCHAR(255),
    CONSTRAINT pk_customer PRIMARY KEY (id)
);

CREATE TABLE customer_device
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    customer_id     BIGINT                                  NOT NULL,
    device_id       BIGINT                                  NOT NULL,
    serial_number   VARCHAR(255),
    additional_info VARCHAR(255),
    external_state  VARCHAR(255),
    CONSTRAINT pk_customerdevice PRIMARY KEY (id)
);

CREATE TABLE device
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    model          VARCHAR(255),
    device_type_id BIGINT                                  NOT NULL,
    producer_id    BIGINT                                  NOT NULL,
    purpose        VARCHAR(255),
    CONSTRAINT pk_device PRIMARY KEY (id)
);

CREATE TABLE device_type
(
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    type_name VARCHAR(255),
    CONSTRAINT pk_devicetype PRIMARY KEY (id)
);

CREATE TABLE diagnostic
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    repair_order_id BIGINT                                  NOT NULL,
    started_at      TIMESTAMP WITHOUT TIME ZONE,
    finished_at     TIMESTAMP WITHOUT TIME ZONE,
    reason          VARCHAR(255),
    solution        VARCHAR(255),
    CONSTRAINT pk_diagnostic PRIMARY KEY (id)
);

CREATE TABLE producer
(
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name VARCHAR(255),
    CONSTRAINT pk_producer PRIMARY KEY (id)
);

CREATE TABLE repair_order
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    number             VARCHAR(255),
    price              DECIMAL(11, 2),
    created_at         TIMESTAMP WITHOUT TIME ZONE,
    customer_device_id BIGINT                                  NOT NULL,
    problem            VARCHAR(255),
    status             VARCHAR(50)                             NOT NULL,
    CONSTRAINT pk_repairorder PRIMARY KEY (id)
);

CREATE TABLE repair_service
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    service_id      BIGINT                                  NOT NULL,
    repair_order_id BIGINT                                  NOT NULL,
    started_at      TIMESTAMP WITHOUT TIME ZONE,
    finished_at     TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT pk_repairservice PRIMARY KEY (id)
);

CREATE TABLE service
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    service_name   VARCHAR(255),
    service_price  DECIMAL(10, 2),
    device_type_id BIGINT                                  NOT NULL,
    CONSTRAINT pk_service PRIMARY KEY (id)
);

